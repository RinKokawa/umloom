import { expect, test } from '@playwright/test'

test('swap directed endpoints and keep each multiplicity with its class, including staged edits', async ({ page }) => {
  await page.goto('/')
  const source = page.getByLabel('PlantUML source')
  const initial = '@startuml\nclass A\nclass B\nA "1" --> "0..*" B : owns\n@enduml'
  await source.fill(initial)
  await page.getByRole('button', { name: '编辑关联 A 到 B：owns' }).click()
  await page.getByLabel('关系名称').fill('tracks')
  const swap = page.getByRole('button', { name: '交换起点和终点' })
  await swap.focus(); await page.keyboard.press('Enter')
  await expect(page.getByLabel('起点类')).toHaveValue('B')
  await expect(page.getByLabel('起点多重性')).toHaveValue('0..*')
  await expect(page.getByLabel('终点类')).toHaveValue('A')
  await expect(page.getByLabel('终点多重性')).toHaveValue('1')
  await expect(page.getByLabel('关联方向')).toHaveValue('ClassUnidirectional')
  await expect(page.getByLabel('关系名称')).toHaveValue('tracks')
  await expect(source).toHaveValue(initial)
  await expect(source).toHaveAttribute('readonly', '')
  page.on('dialog', dialog => void dialog.accept())
  await page.reload()
  await expect(page.getByLabel('起点类')).toHaveValue('B')
  await expect(page.getByLabel('起点多重性')).toHaveValue('0..*')
  await expect(page.getByLabel('关系名称')).toHaveValue('tracks')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/B "0\.\.\*" --> "1" A : tracks/)
  await page.getByLabel('源码格式').selectOption('mermaid')
  await expect(page.getByLabel('Mermaid source')).toHaveValue(/B "0\.\.\*" --> "1" A : tracks/)
})

test('swap twice and undo preserve a self-association and other staged fields', async ({ page }) => {
  await page.goto('/')
  const source = page.getByLabel('PlantUML source')
  const initial = '@startuml\nclass Node\nNode "1" --> "*" Node : child\n@enduml'
  await source.fill(initial)
  await page.getByRole('button', { name: '编辑关联 Node 到 Node：child' }).focus()
  await page.keyboard.press('Enter')
  await page.getByLabel('关系名称').fill('parent')
  const swap = page.getByRole('button', { name: '交换起点和终点' })
  await swap.click()
  await expect(page.getByLabel('起点多重性')).toHaveValue('*')
  await expect(page.getByLabel('终点多重性')).toHaveValue('1')
  await swap.click()
  await expect(page.getByLabel('起点多重性')).toHaveValue('1')
  await expect(page.getByLabel('终点多重性')).toHaveValue('*')
  await expect(page.getByLabel('关系名称')).toHaveValue('parent')
  await page.getByRole('button', { name: '撤销编辑' }).click()
  await expect(page.getByLabel('关系名称')).toHaveValue('child')
  await expect(source).toHaveValue(initial)
})
