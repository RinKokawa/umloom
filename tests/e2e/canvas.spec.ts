import { expect, test } from '@playwright/test'

test('only PlantUML and Mermaid formats are available', async ({ page }) => {
  await page.goto('/')
  const format = page.getByLabel('源码格式')
  await expect(format.locator('option')).toHaveText(['PlantUML', 'Mermaid'])
  await format.selectOption('mermaid')
  await expect(page.getByRole('textbox', { name: 'Mermaid source' })).toHaveValue(/classDiagram/)
  await format.selectOption('plantuml')
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/@startuml/)
})

test('canvas updates both multiplicities and source; no external iframe is used', async ({ page }) => {
  await page.goto('/')
  await expect(page.locator('iframe')).toHaveCount(0)
  await page.getByRole('button', { name: '编辑关联 Classroom 到 Student' }).click()
  await page.getByLabel('起点多重性').fill('0..1')
  await page.getByLabel('终点多重性').fill('1..*')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(source).toHaveAttribute('readonly', '')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/Classroom "0\.\.1" -- "1\.\.\*" Student/)
  await page.reload()
  await expect(source).toHaveValue(/Classroom "0\.\.1" -- "1\.\.\*" Student/)
})

test('unfinished source preserves last canvas and is restored', async ({ page }) => {
  await page.goto('/')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nenum Student\n@enduml')
  await expect(page.locator('footer')).toContainText('源码尚未同步')
  await expect(page.getByRole('button', { name: '添加元素' })).toBeDisabled()
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toBeVisible()
  await page.reload()
  await expect(source).toHaveValue(/enum Student/)
  await expect(page.locator('footer')).toContainText('源码尚未同步')
  await source.fill('@startuml\nclass Student\n@enduml')
  await expect(page.locator('footer')).toContainText('已同步')
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toBeVisible()
})

test('unapplied panel changes survive reload and can be applied', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Learner')
  page.on('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Learner')
  await expect(page.locator('footer')).toContainText('未应用')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/class Learner/)
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/Classroom "1" -- "0\.\.\*" Learner/)
})

test('add classes, relations and edit members; switch source format', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '添加元素' }).click()
  await page.getByRole('button', { name: '添加类', exact: true }).click()
  await page.getByLabel('类名', { exact: true }).fill('Course')
  await page.getByRole('button', { name: '添加属性' }).click()
  await page.getByLabel('属性 1 名称').fill('title')
  await page.getByLabel('属性 1 类型').fill('String')
  await page.getByRole('button', { name: '添加方法' }).click()
  await page.getByLabel('方法 1 名称').fill('open')
  await page.getByLabel('方法 1 返回类型').fill('void')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/class Course/)
  await page.getByLabel('源码格式').selectOption('mermaid')
  await expect(page.getByRole('textbox', { name: 'Mermaid source' })).toHaveValue(/class Course/)
  await page.getByRole('button', { name: '添加关系' }).click()
  await page.getByLabel('终点类').selectOption('Course')
  await page.getByLabel('终点多重性').fill('0..*')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.getByRole('textbox', { name: 'Mermaid source' })).toHaveValue(/Course/)
})

test('mobile switches between canvas and source without horizontal page overflow', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/')
  await page.getByRole('button', { name: '适应内容' }).click()
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Learner')
  await page.getByRole('button', { name: '应用更改' }).click()
  await page.getByRole('button', { name: '源码', exact: true }).click()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/class Learner/)
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390)
})
