test('invalid shared library remains untouched and is included in backups', async ({ page }) => {
  const raw = '{invalid library'
  await page.addInitScript(value => localStorage.setItem('umloom-icon-library-v1', value), raw)
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('本地图标库无法读取')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByLabel('类图标', { exact: true }).selectOption('lucide:book-open')
  expect(await page.evaluate(() => localStorage.getItem('umloom-icon-library-v1'))).toBe(raw)
  const waiting = page.waitForEvent('download')
  await page.getByRole('button', { name: '备份草稿' }).click()
  const backup = JSON.parse(await readFile((await (await waiting).path())!, 'utf8'))
  expect(backup.icons.library.unreadableOriginal).toBe(raw)
})

test('invalid saved icon data is preserved instead of overwritten', async ({ page }) => {
  const raw = '{corrupt icon settings'
  await page.addInitScript(value => localStorage.setItem('umloom-class-icons-v1:playground', value), raw)
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('本地图标设置无法读取')
  await expect(page.getByRole('button', { name: '隐藏类图标' })).toBeDisabled()
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await expect(page.getByLabel('类图标', { exact: true })).toBeDisabled()
  expect(await page.evaluate(() => localStorage.getItem('umloom-class-icons-v1:playground'))).toBe(raw)
  const waiting = page.waitForEvent('download')
  await page.getByRole('button', { name: '备份草稿' }).click()
  const backup = JSON.parse(await readFile((await (await waiting).path())!, 'utf8'))
  expect(backup.icons.unreadableOriginal).toBe(raw)
})
