import { expect, test } from '@playwright/test'
import { readFile } from 'node:fs/promises'

test('local icon matching is offline, manual choices persist and do not alter the model', async ({ page }) => {
  let requests = 0
  await page.route('https://api.iconify.design/**', async route => { requests++; await route.abort() })
  await page.goto('/')
  const source = page.getByLabel('PlantUML source')
  const text = '@startuml\nclass Student\nclass AircraftType\nclass Unmapped\n@enduml'
  await source.fill(text)
  const student = page.getByRole('button', { name: '编辑类 Student' })
  const type = page.getByRole('button', { name: '编辑类 AircraftType' })
  const unknown = page.getByRole('button', { name: '编辑类 Unmapped' })
  await expect(student.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:graduation-cap')
  await expect(type.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'umloom:aircraft-model')
  await expect(unknown.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:box')
  await expect(type.locator('.class-icon-badge path')).toHaveCount(1)
  expect(requests).toBe(0)
  await page.getByRole('button', { name: '适应内容' }).click()
  await unknown.click()
  await page.getByLabel('类图标', { exact: true }).selectOption('lucide:book-open')
  await expect(unknown.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:book-open')
  await expect(source).toHaveValue(text)
  await page.getByRole('button', { name: '隐藏类图标' }).click()
  await expect(student.locator('.class-icon-badge')).toHaveCount(0)
  await expect(source).toHaveValue(text)
  await page.reload()
  await expect(page.getByRole('button', { name: '显示类图标' })).toBeVisible()
  await page.getByRole('button', { name: '显示类图标' }).click()
  await expect(unknown.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:book-open')
  await page.getByRole('button', { name: '适应内容' }).click()
  await unknown.click()
  await page.getByLabel('类图标', { exact: true }).selectOption('none')
  await expect(unknown.locator('.class-icon-badge')).toHaveCount(0)
  await page.getByLabel('类图标', { exact: true }).selectOption('auto')
  await expect(unknown.locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:box')
  await page.getByLabel('类图标', { exact: true }).selectOption('umloom:surgery-room')
  await page.getByLabel('类名', { exact: true }).fill('Renamed')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.getByRole('button', { name: '编辑类 Renamed' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'umloom:surgery-room')
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '备份草稿' }).click()
  const download = await downloadPromise
  const backup = JSON.parse(await readFile((await download.path())!, 'utf8'))
  expect(backup.icons.choices.Renamed).toEqual({ kind: 'umloom', id: 'surgery-room' })
  expect(requests).toBe(0)
})

test('Iconify search requires a click, accepts only safe Tabler SVG and caches a selected icon', async ({ page }) => {
  const requests: string[] = []
  await page.route('https://api.iconify.design/**', async route => {
    const url = new URL(route.request().url()); requests.push(url.pathname)
    if (url.pathname === '/search') {
      expect(url.searchParams.get('query')).toBe('Student')
      expect(url.searchParams.get('prefix')).toBe('tabler')
      await route.fulfill({ json: { icons: ['tabler:plane', 'tabler:evil', 'other:unsafe'] } })
    } else {
      expect(url.pathname).toBe('/tabler.json')
      await route.fulfill({ json: { prefix: 'tabler', width: 24, height: 24, icons: {
        plane: { body: '<path d="M2 12h20" fill="none" stroke="currentColor"/>' },
        evil: { body: '<path d="M0 0" onload="alert(1)"/><script>alert(1)</script>' },
      } } })
    }
  })
  await page.goto('/')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByText('搜索开源图标（需联网）').click()
  await expect(page.getByText(/关键词将发送到 Iconify/)).toBeVisible()
  expect(requests).toEqual([])
  await page.getByRole('button', { name: '搜索图标' }).click()
  await expect(page.getByRole('button', { name: '选择图标 plane' })).toBeVisible()
  await expect(page.getByRole('button', { name: '选择图标 evil' })).toHaveCount(0)
  await page.getByRole('button', { name: '选择图标 plane' }).click()
  const badge = page.getByRole('button', { name: '编辑类 Student' }).locator('.class-icon-badge')
  await expect(badge).toHaveAttribute('data-icon', 'iconify:plane')
  await expect(badge.locator('path')).toHaveAttribute('d', 'M2 12h20')
  await expect(page.getByLabel('类图标', { exact: true })).toHaveValue('iconify:plane')
  expect(requests).toEqual(['/search', '/tabler.json'])
  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '备份草稿' }).click()
  const backup = JSON.parse(await readFile((await (await downloadPromise).path())!, 'utf8'))
  expect(backup.icons.library.icons[0].id).toBe('plane')
  expect(backup.icons.library.licenseText).toContain('Paweł Kuna')
  await page.reload()
  await expect(badge).toHaveAttribute('data-icon', 'iconify:plane')
  await expect(badge.locator('path')).toHaveAttribute('d', 'M2 12h20')
  expect(requests).toHaveLength(2)
  await page.getByRole('button', { name: '编辑类 Classroom' }).click()
  await page.getByLabel('类图标', { exact: true }).selectOption('iconify:plane')
  await expect(page.getByRole('button', { name: '编辑类 Classroom' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'iconify:plane')
  await page.getByRole('button', { name: '从本地图标库移除' }).click()
  await expect(page.getByRole('button', { name: '编辑类 Classroom' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'iconify:plane')
  await expect(badge).toHaveAttribute('data-icon', 'iconify:plane')
  expect(requests).toHaveLength(2)
})

test('abandoned online searches cannot change a different class', async ({ page }) => {
  await page.route('https://api.iconify.design/**', async route => {
    await new Promise(resolve => setTimeout(resolve, 500))
    await route.fulfill({ json: { icons: ['tabler:plane'] } }).catch(() => {})
  })
  await page.goto('/')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByText('搜索开源图标（需联网）').click()
  await page.getByRole('button', { name: '搜索图标' }).click()
  await page.getByRole('button', { name: '编辑类 Classroom' }).click()
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Classroom')
  await page.waitForTimeout(700)
  await expect(page.getByRole('button', { name: '选择图标 plane' })).toHaveCount(0)
  await expect(page.getByRole('button', { name: '编辑类 Classroom' }).locator('.class-icon-badge')).toHaveAttribute('data-icon', 'lucide:building-2')
})

