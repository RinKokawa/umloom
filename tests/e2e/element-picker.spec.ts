import { expect, test } from '@playwright/test'

test('element picker supports keyboard navigation, Escape, and outside dismissal', async ({ page }) => {
  await page.goto('/')
  const trigger = page.getByRole('button', { name: '添加元素' })
  const picker = page.getByRole('group', { name: '可添加的元素' })
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
  await expect(picker).toBeHidden()
  await trigger.focus()
  await page.keyboard.press('Enter')
  await expect(trigger).toHaveAttribute('aria-expanded', 'true')
  await expect(picker).toBeVisible()
  await page.keyboard.press('ArrowDown')
  await expect(page.getByRole('button', { name: '添加类', exact: true })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: '添加接口', exact: true })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(picker).toBeHidden()
  await expect(trigger).toBeFocused()
  await trigger.click()
  await page.locator('.pane-header').first().click()
  await expect(picker).toBeHidden()
  await expect(trigger).toHaveAttribute('aria-expanded', 'false')
})

test('creating from the picker protects unapplied edits', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByLabel('类名', { exact: true }).fill('Learner')
  await page.getByRole('button', { name: '添加元素' }).click()
  page.once('dialog', dialog => dialog.dismiss())
  await page.getByRole('button', { name: '添加类', exact: true }).click()
  await expect(page.getByLabel('类名', { exact: true })).toHaveValue('Learner')
  await expect(page.getByRole('button', { name: '编辑类 Class1' })).toHaveCount(0)
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveAttribute('readonly', '')
  await expect(page.getByRole('button', { name: '添加元素' })).toHaveAttribute('aria-expanded', 'false')
})

test('mobile picker fits the viewport and adds an interface', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 740 })
  await page.goto('/')
  await page.getByRole('button', { name: '添加元素' }).click()
  const panel = page.getByRole('group', { name: '可添加的元素' })
  await expect(panel).toBeVisible()
  const bounds = (await panel.boundingBox())!
  expect(bounds.x).toBeGreaterThanOrEqual(0)
  expect(bounds.x + bounds.width).toBeLessThanOrEqual(320)
  await page.getByRole('button', { name: '添加接口', exact: true }).click()
  await expect(page.getByRole('button', { name: '编辑接口 Interface1' })).toBeVisible()
  await expect(page.getByLabel('接口名')).toHaveValue('Interface1')
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(320)
})
