import { expect, test } from '@playwright/test'

test('edit attributes, methods and structured parameters without writing UML syntax', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  const panel = page.getByRole('complementary', { name: '类属性面板' })
  await expect(panel.getByText('暂无属性')).toBeVisible()
  await expect(panel.getByText('暂无方法')).toBeVisible()
  await page.getByRole('button', { name: '添加属性' }).click()
  await page.getByLabel('属性 1 名称').fill('name')
  await page.getByLabel('属性 1 类型').fill('String')
  await page.getByLabel('属性 1 可见性').selectOption('-')
  await page.getByRole('button', { name: '添加方法' }).click()
  await page.getByLabel('方法 1 名称').fill('find')
  await page.getByLabel('方法 1 返回类型').fill('Boolean')
  await page.getByRole('button', { name: '为方法 1 添加参数' }).click()
  await page.getByLabel('方法 1 参数 1 名称').fill('id')
  await page.getByLabel('方法 1 参数 1 类型').fill('String')
  await page.getByRole('button', { name: '应用更改' }).click()
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await expect(source).toHaveValue(/- name: String/)
  await expect(source).toHaveValue(/\+ find\(id: String\): Boolean/)
  await expect(page.getByRole('button', { name: '编辑类 Student' })).toContainText('name: String')
  await page.getByLabel('源码格式').selectOption('mermaid')
  await expect(page.getByRole('textbox', { name: 'Mermaid source' })).toHaveValue(/find\(id: String\) Boolean/)
})

test('invalid or incomplete member fields remain staged across refresh', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByRole('button', { name: '添加属性' }).click()
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.locator('.inspector-error')).toContainText('属性名称')
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).not.toHaveValue(/- :/)
  await page.getByLabel('属性 1 名称').fill('age')
  await page.getByLabel('属性 1 类型').fill('Integer')
  page.on('dialog', dialog => dialog.accept())
  await page.reload()
  await expect(page.getByLabel('属性 1 名称')).toHaveValue('age')
  await expect(page.getByLabel('属性 1 类型')).toHaveValue('Integer')
  await expect(page.locator('footer')).toContainText('未应用')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(page.getByRole('textbox', { name: 'PlantUML source' })).toHaveValue(/- age: Integer/)
})

test('unsupported existing declarations remain intact when renaming a class', async ({ page }) => {
  await page.goto('/')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nclass Student {\n- items: List<String>\n+ run(String value): void\n}\n@enduml')
  await expect(page.locator('footer')).toContainText('已同步')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await expect(page.getByText('此声明暂不能结构化编辑，原文会保留。')).toHaveCount(2)
  await page.getByLabel('类名', { exact: true }).fill('Learner')
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).toHaveValue(/class Learner/)
  await expect(source).toHaveValue(/- items: List<String>/)
  await expect(source).toHaveValue(/\+ run\(String value\): void/)
})

test('deleting a member is staged until applied and undo restores it', async ({ page }) => {
  await page.goto('/')
  const source = page.getByRole('textbox', { name: 'PlantUML source' })
  await source.fill('@startuml\nclass Student {\n- name: String\n}\n@enduml')
  await expect(page.locator('footer')).toContainText('已同步')
  await page.getByRole('button', { name: '编辑类 Student' }).click()
  await page.getByRole('button', { name: '删除属性 1' }).click()
  await expect(source).toHaveValue(/name: String/)
  await page.getByRole('button', { name: '撤销编辑' }).click()
  await expect(page.getByLabel('属性 1 名称')).toHaveValue('name')
  await page.getByRole('button', { name: '删除属性 1' }).click()
  await page.getByRole('button', { name: '应用更改' }).click()
  await expect(source).not.toHaveValue(/name: String/)
})
